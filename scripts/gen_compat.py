"""Generate the template compatibility list ``docs/user/compatibility.md``.

Reads the built-in templates through :mod:`suncore.templates` (the same loader the app uses)
and the English names from the frontend catalogue ``en.json``. The output is deterministic
(sorted by kind, then id) and contains no dates. Run via
``uv run python scripts/gen_compat.py [--check] [output_file]``; ``--check`` exits 1 if the
committed file is missing or outdated (CI drift guard, like ``gen_schemas.py``).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from suncore.templates.loader import load_templates
from suncore.templates.models import Template

ROOT = Path(__file__).resolve().parents[1]
TEMPLATES = ROOT / "templates"
EN_CATALOGUE = ROOT / "frontend" / "src" / "lib" / "i18n" / "locales" / "en.json"
DEFAULT_OUTPUT = ROOT / "docs" / "user" / "compatibility.md"

KIND_ORDER = ("device", "tariff", "forecast", "region")
KIND_TITLES = {
    "device": "Devices",
    "tariff": "Tariffs",
    "forecast": "PV forecasts",
    "region": "Regions",
}
DASH = "\N{EN DASH}"
NOT_TESTED = "not tested on hardware"
TABLE_HEAD = (
    "| Id | Kind | Name | Integration / platforms | Capabilities | Tested with | Unverified |\n"
    "|---|---|---|---|---|---|---|"
)

HEADER = """\
<!-- Generated by scripts/gen_compat.py from templates/. Do not edit by hand. -->

# Compatibility list

This list is generated from the built-in templates in `templates/`. A template describes how
SunCore finds the entities of a device, tariff or forecast source and which defaults it uses.
It does **not** mean that the device is controlled yet: until the controller arrives
(Phase 3) SunCore only observes, and all devices run in shadow mode.

- **Tested with** names the integration versions a contributor verified the template against
  on a running Home Assistant. *not tested on hardware* means the template was written from
  the integration source and has only run in the simulator.
- **Unverified** is the number of facts the template lists as unverified. Open the template
  file to read them.
- Your own templates (in `/data/templates`) are not listed here. To add a device see
  [Contribute a device template](en/device-templates.md).
"""


def _platforms(template: Template) -> str:
    roles = getattr(template, "roles", None)
    if roles is None:
        return DASH
    found = {p for role in roles.values() for p in (role.matcher.platforms or [])}
    return ", ".join(f"`{p}`" for p in sorted(found)) if found else "any"


def _tested(template: Template) -> str:
    if template.tested_with:
        return ", ".join(f"{t.integration} {t.version}" for t in template.tested_with)
    return DASH if template.kind == "region" else NOT_TESTED


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(templates_dir: Path = TEMPLATES, catalogue_path: Path = EN_CATALOGUE) -> str:
    """Return the Markdown of the compatibility list."""
    catalogue: dict[str, str] = json.loads(catalogue_path.read_text(encoding="utf-8"))
    catalog = load_templates(templates_dir)
    lines = [HEADER]
    for kind in KIND_ORDER:
        items = sorted(catalog.of_kind(kind), key=lambda t: t.id)
        if not items:
            continue
        lines.extend([f"## {KIND_TITLES[kind]}\n", TABLE_HEAD])
        for t in items:
            caps = ", ".join(f"`{c.value}`" for c in sorted(t.capabilities, key=str)) or DASH
            row = [
                f"`{t.id}`",
                t.kind,
                catalogue.get(t.name, t.name),
                _platforms(t),
                caps,
                _tested(t),
                str(len(t.unverified)),
            ]
            lines.append("| " + " | ".join(_cell(c) for c in row) + " |")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", nargs="?", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="fail if the file is outdated")
    args = parser.parse_args(argv)
    content = render()
    out: Path = args.output
    if args.check:
        if not out.exists() or out.read_text(encoding="utf-8") != content:
            sys.stderr.write(f"{out} is out of date\nrun: uv run python scripts/gen_compat.py\n")
            return 1
        print("gen_compat: compatibility list up to date")
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(content, encoding="utf-8")
    print(f"gen_compat: wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

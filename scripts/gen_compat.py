"""Generate the template compatibility lists ``docs/user/<lang>/compatibility.md`` (en, de).

Reads the built-in templates through :mod:`suncore.templates` (the same loader the app uses)
and the names from the frontend catalogue of the language. The output is deterministic
(sorted by kind, then id) and contains no dates. Run via
``uv run python scripts/gen_compat.py [--check]``; ``--check`` exits 1 if a committed file is
missing or outdated (CI drift guard, like ``gen_schemas.py``). The old single file
``docs/user/compatibility.md`` is gone (a root file clashes with the folder layout).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from suncore.templates.loader import load_templates
from suncore.templates.models import Template

ROOT = Path(__file__).resolve().parents[1]
TEMPLATES = ROOT / "templates"
LOCALES = ROOT / "frontend" / "src" / "lib" / "i18n" / "locales"
OUTPUTS = {
    "en": ROOT / "docs" / "user" / "en" / "compatibility.md",
    "de": ROOT / "docs" / "user" / "de" / "compatibility.md",
}

KIND_ORDER = ("device", "battery", "inverter", "tariff", "forecast", "region")
DASH = "\N{EN DASH}"

TEXT = {
    "en": {
        "kinds": {
            "device": "Devices",
            "battery": "Batteries",
            "inverter": "Inverter limits",
            "tariff": "Tariffs",
            "forecast": "PV forecasts",
            "region": "Regions",
        },
        "not_tested": "not tested on hardware",
        "any": "any",
        "head": (
            "| Id | Kind | Name | Integration / platforms | Capabilities | Tested with "
            "| Unverified |\n|---|---|---|---|---|---|---|"
        ),
        "header": """\
<!-- Generated by scripts/gen_compat.py from templates/. Do not edit by hand. -->

# Compatibility list

This list is generated from the built-in templates in `templates/`. A template describes how
SunCore finds the entities of a device, tariff or forecast source and which defaults it uses.
It does **not** mean that the device is controlled: every device starts in shadow mode, and
a template only tested in the simulator has never run against real hardware.

- **Tested with** names the integration versions a contributor verified the template against
  on a running Home Assistant. *not tested on hardware* means the template was written from
  the integration source and has only run in the simulator.
- **Unverified** is the number of facts the template lists as unverified. Open the template
  file to read them.
- **Shiftable programs behind a smart plug:** add a Home Assistant automation that switches
  the plug on when it has been off for many hours, in case SunCore is not running while it
  waits (see [Surplus control](surplus-control.md), "Shiftable programs").
- Your own templates (in `/data/templates`) are not listed here. To add a device see
  [Contribute a device template](device-templates.md).
""",
    },
    "de": {
        "kinds": {
            "device": "Geräte",
            "battery": "Batterien",
            "inverter": "Wechselrichter-Grenzen",
            "tariff": "Tarife",
            "forecast": "PV-Prognosen",
            "region": "Regionen",
        },
        "not_tested": "nicht auf Hardware getestet",
        "any": "beliebig",
        "head": (
            "| Id | Art | Name | Integration / Plattformen | Fähigkeiten | Getestet mit "
            "| Ungeprüft |\n|---|---|---|---|---|---|---|"
        ),
        "header": """\
<!-- Generiert von scripts/gen_compat.py aus templates/. Nicht von Hand ändern. -->

# Kompatibilitätsliste

Diese Liste wird aus den eingebauten Vorlagen in `templates/` erzeugt. Eine Vorlage beschreibt,
wie SunCore die Entitäten eines Geräts, Tarifs oder einer Prognosequelle findet und welche
Standardwerte es nutzt. Sie heißt **nicht**, dass das Gerät gesteuert wird: Jedes Gerät startet im
Schattenmodus, und eine Vorlage, die nur im Simulator getestet wurde, lief nie an echter Hardware.

- **Getestet mit** nennt die Integrationsversionen, gegen die jemand die Vorlage auf einem
  laufenden Home Assistant geprüft hat. *nicht auf Hardware getestet* heißt: Die Vorlage wurde aus
  dem Quelltext der Integration geschrieben und lief nur im Simulator.
- **Ungeprüft** ist die Zahl der Tatsachen, die die Vorlage als ungeprüft aufführt. Sie stehen in
  der Vorlagendatei.
- **Verschiebbare Programme hinter einer Steckdose:** Lege eine Home-Assistant-Automatisierung an,
  die die Steckdose einschaltet, wenn sie viele Stunden aus war, falls SunCore nicht läuft, während
  das Programm wartet (siehe [Überschussregelung](surplus-control.md), "Verschiebbare Programme").
- Eigene Vorlagen (in `/data/templates`) stehen nicht in dieser Liste. Wie du ein Gerät beiträgst,
  steht unter [Gerätevorlage beitragen](device-templates.md).
""",
    },
}


def _platforms(template: Template, lang: str) -> str:
    roles = getattr(template, "roles", None)
    if roles is None:
        return DASH
    found = {p for role in roles.values() for p in (role.matcher.platforms or [])}
    return ", ".join(f"`{p}`" for p in sorted(found)) if found else TEXT[lang]["any"]


def _tested(template: Template, lang: str) -> str:
    if template.tested_with:
        return ", ".join(f"{t.integration} {t.version}" for t in template.tested_with)
    return DASH if template.kind == "region" else TEXT[lang]["not_tested"]


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(lang: str, templates_dir: Path = TEMPLATES, locales: Path = LOCALES) -> str:
    """Return the Markdown of the compatibility list in ``lang`` (``en`` or ``de``)."""
    words = TEXT[lang]
    catalogue: dict[str, str] = json.loads((locales / f"{lang}.json").read_text(encoding="utf-8"))
    catalog = load_templates(templates_dir)
    lines = [words["header"]]
    for kind in KIND_ORDER:
        items = sorted(catalog.of_kind(kind), key=lambda t: t.id)
        if not items:
            continue
        lines.extend([f"## {words['kinds'][kind]}\n", words["head"]])
        for t in items:
            caps = ", ".join(f"`{c.value}`" for c in sorted(t.capabilities, key=str)) or DASH
            row = [
                f"`{t.id}`",
                t.kind,
                catalogue.get(t.name, t.name),
                _platforms(t, lang),
                caps,
                _tested(t, lang),
                str(len(t.unverified)),
            ]
            lines.append("| " + " | ".join(_cell(c) for c in row) + " |")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if a file is outdated")
    args = parser.parse_args(argv)
    status = 0
    for lang, out in OUTPUTS.items():
        content = render(lang)
        if args.check:
            if not out.exists() or out.read_text(encoding="utf-8") != content:
                sys.stderr.write(
                    f"{out} is out of date\nrun: uv run python scripts/gen_compat.py\n"
                )
                status = 1
            continue
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(content, encoding="utf-8")
        print(f"gen_compat: wrote {out}")
    if args.check and status == 0:
        print("gen_compat: compatibility lists up to date")
    return status


if __name__ == "__main__":
    sys.exit(main())

def _value(value: ParamValue, lang: str) -> str:
    words = TEXT[lang]
    if value is None:
        return words["unset"]
    if isinstance(value, bool):
        return words["on" if value else "off"]
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value)


def _range(spec: ParamSpec) -> str:
    if spec.kind == "enum":
        return " / ".join(f"`{c}`" for c in spec.choices)
    if spec.minimum is None or spec.maximum is None:
        return DASH
    return f"{_value(spec.minimum, 'en')} {DASH} {_value(spec.maximum, 'en')}"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _row(spec: ParamSpec, lang: str, catalogue: dict[str, str]) -> str:
    words = TEXT[lang]
    marks = ", ".join(words["tags"][t] for t in ("safety", "restart", "whatif") if t in spec.tags)
    where = (
        words["store_expert"]
        if spec.store == "expert"
        else words["store_config"].format(section=spec.section, path=".".join(spec.path))
    )
    help_text = f"**{catalogue[spec.name_key]}.** {catalogue[spec.help_key]} {where}"
    cells = [
        f"`{spec.key}`",
        spec.kind,
        spec.unit or DASH,
        _value(spec.default, lang),
        _range(spec),
        marks or DASH,
        help_text,
    ]
    return "| " + " | ".join(_cell(c) for c in cells) + " |"


def _wrap(text: str) -> str:
    """Wrap prose lines at 100 columns (markdownlint MD013); headings and comments stay."""
    out: list[str] = []
    for line in text.split("\n"):
        if line.startswith(("<!--", "#")) or len(line) <= 100:
            out.append(line)
        else:
            out.append(textwrap.fill(line, 100, subsequent_indent="  " if line[:2] == "- " else ""))
    return "\n".join(out)


def render(lang: str, locales: Path = LOCALES) -> str:
    """The Markdown of the reference in ``lang`` (``en`` or ``de``)."""
    catalogue: dict[str, str] = json.loads((locales / f"{lang}.json").read_text(encoding="utf-8"))
    # The parameter help lives in its own lazily loaded catalogue.
    catalogue |= json.loads((locales / f"params.{lang}.json").read_text(encoding="utf-8"))
    words = TEXT[lang]
    head = "| " + " | ".join(words["cols"]) + " |\n|" + "---|" * len(words["cols"])
    lines = [_wrap(words["header"])]
    for group in GROUPS:
        rows = [_row(s, lang, catalogue) for s in specs_of_group(group)]
        if rows:
            lines.extend([f"## {words['groups'][group]}\n", head, *rows, ""])
    assert len(REGISTRY) == sum(len(specs_of_group(g)) for g in GROUPS), "ungrouped parameter"
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if a file is outdated")
    args = parser.parse_args(argv)
    status = 0
    for lang, out in OUTPUTS.items():
        content = render(lang)
        if args.check:
            if not out.exists() or out.read_text(encoding="utf-8") != content:
                sys.stderr.write(
                    f"{out} is out of date\nrun: uv run python scripts/gen_params.py\n"
                )
                status = 1
            continue
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(content, encoding="utf-8")
        print(f"gen_params: wrote {out}")
    if args.check and status == 0:
        print("gen_params: parameter reference up to date")
    return status


if __name__ == "__main__":
    sys.exit(main())
